function cloneActivity(activity: DmuActivity): DmuActivity {
  return {
    ...activity,
    faculty: activity.faculty.map((member) => ({ ...member })),
  };
}

export async function fetchMockActivity(activityCode: string): Promise<DmuActivity> {
  const code = activityCode.trim().toUpperCase();
  if (!code) {
    throw new Error("Activity code is required.");
  }

  await new Promise((resolve) => setTimeout(resolve, FETCH_DELAY_MS));

  const activity = ACTIVITIES[code];
  if (!activity) {
    throw new Error("Activity not found.");
  }

  return cloneActivity(activity);
}
